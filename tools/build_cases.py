#!/usr/bin/env python3
"""Export the interactive case explorer's data from a chosen-cases run.

Reads <src>/results.json and the per-case panel PNGs, converts the panels used
by the selected groups to WebP (deduplicated by content, since the input and
tokenization are shared by both prompts of an image), and writes
assets/cases/cases.js. Every budget present in results.json is exported, so
adding B=128/224 runs only requires re-running this script.

    python3 tools/build_cases.py [--src chosen_cases_v2] [--quality 82]

Requires `cwebp` (brew install webp).
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'cases'

# (results.json group, display title, prompt names in display order)
GROUPS = [
    ('TextVQA_0d6143272f078726', 'Two shirts, two sponsors', ['TextVQA_38835', 'TextVQA_38836']),
    ('GQA_n400036', 'Street with a soccer ball', ['GQA_n400036_ball', 'GQA_20652282']),
    ('TextVQA_9469e682447efc81', 'Hot-air balloon', ['TextVQA_36673', 'TextVQA_36673_reg']),
    ('RefCOCO_402041', 'Circus elephants', ['RefCOCO_refcoco_val_15612_44431', 'RefCOCO_refcoco_val_15613_44432']),
    ('MIT', 'MIT Great Dome', ['Custom_mit_text', 'Custom_mit_doors']),
    ('TextVQA_3d27ed4334548acc', 'Football jersey', ['TextVQA_38940', 'TextVQA_38940_sponsor']),
    ('GQA_n170941', 'Breakfast table', ['GQA_20157198', 'GQA_20157006']),
    ('UofT', 'University of Toronto', ['Custom_UofT_convocation_hall', 'Custom_UofT_field']),
]
METHODS = [('varest', 'Varest'), ('core', 'CORE'), ('visionzippp', 'VisionZip++'),
           ('hidrop', 'HiDrop'), ('learnpruner', 'LearnPruner')]


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--src', default=ROOT / 'chosen_cases_v2', type=Path)
    parser.add_argument('--quality', default=82, type=int)
    args = parser.parse_args()
    if not shutil.which('cwebp'):
        raise SystemExit('cwebp not found; install it with `brew install webp`.')

    results = json.loads((args.src / 'results.json').read_text())
    cases = {c['name']: c for c in results['cases']}
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    converted = {}

    def export(case, filename, folder):
        source = args.src / case['dir'] / filename
        digest = hashlib.sha1(source.read_bytes()).hexdigest()[:12]
        if digest not in converted:
            target = OUT / folder / f'{digest}.webp'
            target.parent.mkdir(exist_ok=True)
            subprocess.run(['cwebp', '-quiet', '-q', str(args.quality), str(source), '-o', str(target)], check=True)
            converted[digest] = target.relative_to(ROOT).as_posix()
        return converted[digest]

    groups = []
    for group_id, title, names in GROUPS:
        folder = slug(title)
        prompts = []
        for name in names:
            case = cases[name]
            assert case['group'] == group_id, f'{name} is not in {group_id}'
            methods = {}
            for key, _ in METHODS:
                methods[key] = {
                    str(budget): {
                        'answer': run['answer'], 'ok': run['ok'], 'iou': run.get('iou'),
                        'box': run.get('box'), 'k': run.get('k'), 'info': run['info'],
                        'panels': [[label, export(case, file, folder)] for label, file in run['panels']],
                    }
                    for budget, run in case['methods'].get(key, {}).items()
                }
            prompts.append({
                'name': name, 'label': case['q_label'], 'q': case['q'], 'gt': case['gt'],
                'gtBox': case.get('gt_box'), 'methods': methods,
            })
        first = cases[names[0]]
        groups.append({
            'id': folder, 'title': title, 'bench': first['bench'], 'aspect': first['aspect'],
            'input': export(first, 'input.png', folder), 'prompts': prompts,
        })

    data = {
        'budgets': results['budgets'],
        'methods': [{'key': key, 'label': label} for key, label in METHODS],
        'groups': groups,
    }
    (OUT / 'cases.js').write_text(
        '// Generated by tools/build_cases.py; do not edit by hand.\n'
        f'window.VAREST_CASES = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n')
    size = sum(p.stat().st_size for p in OUT.rglob('*') if p.is_file())
    print(f'{len(groups)} groups, {len(converted)} images, {size / 1e6:.1f} MB -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
