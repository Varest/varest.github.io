#!/usr/bin/env python3
"""Export the Varest budget sweep's data from a budget_sweep.py run.

Reads <src>/<case>/records.json and the per-budget panel PNGs (b<B>_w5.png, b<B>_rel.png, input.png) for the
explorer's scenes, converts them to WebP (deduplicated by content: both questions of an image share the
tokenization panel at every budget), and writes assets/sweep/sweep.js. The first case's budgets are exported; every
other case must include them (extra budgets, such as a B=64 run for the comparison explorer, are skipped). WebP files
are named by the source PNG's content hash: existing ones are kept, only new panels are encoded, and files no longer
referenced are removed.

    python3 tools/build_sweep.py [--src sweep19/varest] [--quality 82]

Requires Pillow with WebP support.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

from build_cases import GROUPS, slug

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'sweep'
SIDE = 672  # budget_sweep.py's padded canvas (24 cells of 28 px); its panels are cropped from it to the image


def crop_box(box, width, height):
    """Box normalized on the padded square -> fractions of the panel, using budget_sweep.py's pixel crop."""
    if box is None:
        return None
    scale = SIDE / max(width, height)
    x0, y0 = round((max(width, height) - width) / 2 * scale), round((max(width, height) - height) / 2 * scale)
    cw, ch = round(width * scale), round(height * scale)
    return [round((box[0] * SIDE - x0) / cw, 4), round((box[1] * SIDE - y0) / ch, 4),
            round((box[2] * SIDE - x0) / cw, 4), round((box[3] * SIDE - y0) / ch, 4)]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--src', default=ROOT / 'sweep19' / 'varest', type=Path)
    parser.add_argument('--quality', default=82, type=int)
    args = parser.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    converted = {}

    def export(source, folder):
        digest = hashlib.sha1(source.read_bytes()).hexdigest()[:12]
        if digest not in converted:
            target = OUT / folder / f'{digest}.webp'
            target.parent.mkdir(exist_ok=True)
            if not target.exists():
                Image.open(source).convert('RGB').save(target, 'WEBP', quality=args.quality, method=6)
            converted[digest] = target.relative_to(ROOT).as_posix()
        return converted[digest]

    groups, budgets = [], None
    for _, title, names in GROUPS:
        folder = slug(title)
        prompts = []
        for name in names:
            case = args.src / name
            record = json.loads((case / 'records.json').read_text())
            image = Image.open(record['image']) if Path(record['image']).exists() else None
            width, height = image.size if image else Image.open(case / 'input.png').size
            refcoco = record['bench'].startswith('RefCOCO')
            if budgets is None:
                budgets = [run['budget'] for run in record['budgets']]
            by_budget = {run['budget']: run for run in record['budgets']}
            missing = [b for b in budgets if b not in by_budget]
            assert not missing, f'{name} has no runs at budgets {missing}'
            runs = {}
            for run in (by_budget[b] for b in budgets):
                b = run['budget']
                runs[str(b)] = {
                    'answer': run['answer'], 'ok': run['ok'], 'iou': round(run['iou'], 3) if refcoco else None,
                    'box': crop_box(run.get('box'), width, height) if refcoco else None,
                    'k': run['k'], 'text': run['k_txt'], 'kept': run['kp'], 'layer': run['rel_layer'],
                    'w5': export(case / f'b{b}_w5.png', folder), 'rel': export(case / f'b{b}_rel.png', folder),
                }
            prompts.append({
                'name': name, 'q': record['q'], 'gt': None if refcoco else record['gt'],
                'gtBox': crop_box(record['gt'], width, height) if refcoco else None, 'runs': runs,
            })
        input_png = args.src / names[0] / 'input.png'
        w, h = Image.open(input_png).size
        groups.append({
            'id': folder, 'title': title, 'bench': json.loads((args.src / names[0] / 'records.json').read_text())['bench'],
            'aspect': round(w / h, 4), 'input': export(input_png, folder), 'prompts': prompts,
        })

    data = {'budgets': budgets, 'groups': groups}
    # Drop panels of scenes or runs that are no longer exported.
    used = {ROOT / path for path in converted.values()}
    for stale in [p for p in OUT.rglob('*.webp') if p not in used]:
        stale.unlink()
    for folder in [d for d in OUT.iterdir() if d.is_dir() and not any(d.iterdir())]:
        folder.rmdir()
    (OUT / 'sweep.js').write_text(
        '// Generated by tools/build_sweep.py; do not edit by hand.\n'
        f'window.VAREST_SWEEP = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n')
    size = sum(p.stat().st_size for p in OUT.rglob('*') if p.is_file())
    print(f'{len(groups)} groups, {len(budgets)} budgets, {len(converted)} images, {size / 1e6:.1f} MB -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
